const toText = (value: unknown) => String(value || '').trim();

const nowIso = () => new Date().toISOString();

const randomSuffix = () => Math.random().toString(36).slice(2, 8);

const resolveCompanyId = (ctx: PipelineContext) => {
  const companyId = toText(ctx.companyId || ctx.bot?.companyId);
  if (!companyId) throw new Error('missing_company_id');
  return companyId;
};

const resolveAdminChatId = (ctx: PipelineContext) => {
  return toText(normalizeBotConfigChatId(ctx.bot?.adminChatId));
};

const sendAdmin = async (ctx: PipelineContext, text: string, replyMarkup?: any) => {
  if (!ctx.bot) return false;
  const adminChatId = resolveAdminChatId(ctx);
  if (!adminChatId) return false;
  await telegramOutbox.sendMessage({
    botId: ctx.bot.id,
    token: ctx.bot.token,
    chatId: adminChatId,
    text,
    replyMarkup,
    companyId: ctx.companyId || ctx.bot.companyId
  });
  return true;
};

const randomInviteCode = () => {
  const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  let code = 'CDL-';
  for (let i = 0; i < 6; i += 1) {
    code += alphabet[Math.floor(Math.random() * alphabet.length)] || 'X';
  }
  return code;
};

const ensureUniqueInviteCode = async () => {
  for (let i = 0; i < 120; i += 1) {
    const code = randomInviteCode();
    const exists = await prisma.partnerCompany.findUnique({
      where: { inviteCode: code },
      select: { id: true }
    });
    if (!exists) return code;
  }
  return `CDL-${Date.now().toString(36).slice(-6).toUpperCase()}`;
};

