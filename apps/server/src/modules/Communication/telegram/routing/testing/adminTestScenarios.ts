export const buildTestPanel = (template: string): TestPanelDefinition => {
  const upper = toText(template).toUpperCase();
  return upper === 'B2B' ? B2B_PANEL : LEAD_PANEL;
};

export const resolveScenarioFromPanelState = (
  panel: unknown,
  idx: number,
  chatId: string
): { ok: true; code: TestScenarioCode } | { ok: false; reason: 'stale' } => {
  if (!panel || typeof panel !== 'object') return { ok: false, reason: 'stale' };
  const data = panel as Record<string, any>;
  if (toText(data.chatId) !== toText(chatId)) return { ok: false, reason: 'stale' };
  const items = Array.isArray(data.items) ? data.items.map((it) => toText(it)).filter(Boolean) : [];
  if (!Number.isFinite(idx) || idx < 0 || idx >= items.length) return { ok: false, reason: 'stale' };
  return { ok: true, code: items[idx] as TestScenarioCode };
};

export const runTestScenario = async (
  ctx: PipelineContext,
  scenarioCode: TestScenarioCode,
  actor: TestScenarioActor
) => {
  switch (scenarioCode) {
    case 'lead_buy':
      await createLeadBuyScenario(ctx, actor);
      return { ok: true as const };
    case 'lead_sell':
      await createLeadSellScenario(ctx, actor);
      return { ok: true as const };
    case 'support':
      await createSupportScenario(ctx, actor);
      return { ok: true as const };
    case 'b2b_reg_new':
      await createB2BRegNewScenario(ctx, actor);
      return { ok: true as const };
    case 'b2b_reg_agent':
      await createB2BRegAgentScenario(ctx, actor);
      return { ok: true as const };
    case 'b2b_request':
      await createB2BRequestScenario(ctx, actor);
      return { ok: true as const };
    case 'b2b_sell_form':
      await createB2BSellFormScenario(ctx, actor);
      return { ok: true as const };
    case 'b2b_sell_inv':
      await createB2BSellInventoryScenario(ctx, actor);
      return { ok: true as const };
    case 'b2b_fit':
      await createB2BFitScenario(ctx, actor);
      return { ok: true as const };
    default:
      return { ok: false as const, message: 'unsupported_scenario' };
  }
};
